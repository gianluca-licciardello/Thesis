#!/usr/bin/env python3
"""
run_experiment.py — full pipeline: inner 5-fold CV on train set → select best → test.

Protocol:
  1. Annotation files must be pre-generated by preprocess_ppb.py with --fold=<outer_fold>.
  2. For each inner CV fold k (0..n_inner_folds-1):
       train.py is called with cv{k}_train and cv{k}_val annotation files.
       The best checkpoint is saved to inner_fold_{k}/checkpoint/.
  3. After all inner folds, test.py is called in CV mode: it auto-selects the fold with
     the highest val balanced accuracy and evaluates it once on the fixed held-out test set.

Usage:
  python run_experiment.py \\
    --annotation_prefix annotation/PPB_CIR_V_DB_rgb_112_5s \\
    --outer_fold 0 \\
    --db_pkl_path data/db_features_5s_stride5s.pkl \\
    --epochs 75 -b 32 -j 8

Annotation files expected (generated by preprocess_ppb.py --fold <outer_fold>):
  {annotation_prefix}_test_fold{outer_fold}.txt
  {annotation_prefix}_cv{k}_train_fold{outer_fold}.txt   for k in 0..n_inner_folds-1
  {annotation_prefix}_cv{k}_val_fold{outer_fold}.txt     for k in 0..n_inner_folds-1

Output structure:
  results/<run_name>/
  ├── metadata.json
  ├── inner_fold_0/
  │   ├── log/        ← train.py log + curve for inner fold 0
  │   └── checkpoint/ ← best + last checkpoint for inner fold 0
  ├── inner_fold_1/ ... inner_fold_{n-1}/
  └── eval/
      ├── eval-log.txt
      ├── combined-figure.png
      └── eval-report.md
"""

import argparse
import datetime
import glob
import json
import os
import re
import subprocess
import sys

DECNET_ROOT = os.path.dirname(os.path.abspath(__file__))
PYTHON      = sys.executable


# ---------------------------------------------------------------------------
# Directory helpers
# ---------------------------------------------------------------------------

def resolve_experiment_dir(results_dir, run_name):
    """
    Return the path to use for this experiment.
    Appends a timestamp if a completed experiment already exists there.
    """
    candidate = os.path.join(results_dir, run_name)
    if os.path.isfile(os.path.join(candidate, 'metadata.json')):
        ts = datetime.datetime.now().strftime('%Y-%m-%d_%H-%M-%S')
        candidate = os.path.join(results_dir, f'{run_name}_{ts}')
    return os.path.abspath(candidate)


# ---------------------------------------------------------------------------
# Metric parsing
# ---------------------------------------------------------------------------

def parse_train_metrics(log_dir):
    """Return dict with best_val_balanced_acc_pct from the train.py log."""
    logs = sorted(glob.glob(os.path.join(log_dir, '*-log.txt')))
    if not logs:
        return {}
    best_acc = None
    with open(logs[-1]) as f:
        for line in f:
            m = re.search(r'The best balanced accuracy \(macro\):\s*([\d.]+)', line)
            if m:
                best_acc = float(m.group(1))
    return {'best_val_balanced_acc_pct': round(best_acc, 4)} if best_acc is not None else {}


def parse_eval_metrics(eval_dir):
    """Return per-branch Acc-7, F1-macro, Acc-bal, F1-wtd from the test.py eval log."""
    log_path = os.path.join(eval_dir, 'eval-log.txt')
    if not os.path.exists(log_path):
        return {}
    with open(log_path) as f:
        content = f.read()

    results = {}
    for branch in ['Fused', 'Visual', 'DB']:
        key = branch.lower()
        m = re.search(
            rf'\b{branch}\b\s+([\d.]+)%\s+([\d.]+)%\s+([\d.]+)%\s+([\d.]+)%', content)
        if m:
            results[f'{key}_acc7_pct']     = round(float(m.group(1)), 4)
            results[f'{key}_f1_macro_pct'] = round(float(m.group(2)), 4)
            results[f'{key}_acc_bal_pct']  = round(float(m.group(3)), 4)
            results[f'{key}_f1_wtd_pct']   = round(float(m.group(4)), 4)
    return results


# ---------------------------------------------------------------------------
# Subprocess runner
# ---------------------------------------------------------------------------

def run_step(cmd, label):
    """Run cmd as a subprocess with live output. Returns the exit code."""
    sep = '=' * 62
    print(f'\n{sep}')
    print(f'  {label}')
    print(f'  {" ".join(str(c) for c in cmd)}')
    print(f'{sep}\n', flush=True)
    return subprocess.run(cmd, cwd=DECNET_ROOT).returncode


# ---------------------------------------------------------------------------
# Metadata I/O
# ---------------------------------------------------------------------------

def write_metadata(path, data):
    with open(path, 'w') as f:
        json.dump(data, f, indent=2)


def relpath(abs_path, base):
    try:
        return os.path.relpath(abs_path, base)
    except ValueError:
        return abs_path


# ---------------------------------------------------------------------------
# Build train command
# ---------------------------------------------------------------------------

def build_train_cmd(args, train_txt, val_txt, output_dir):
    cmd = [
        PYTHON, 'train.py',
        '--train_txt_path', train_txt,
        '--val_txt_path',   val_txt,
        '--output_dir',     output_dir,
        '-t',               str(args.t),
        '--contrast',       args.contrast,
        '-b',               str(args.batch_size),
        '-j',               str(args.workers),
        '--epochs',         str(args.epochs),
        '--lr',             str(args.lr),
        '--momentum',       str(args.momentum),
        '--wd',             str(args.wd),
        '--noise_A',        str(args.noise_A),
        '--data_set',       str(args.data_set),
        '--s_former_depth', str(args.s_former_depth),
        '--t_former_depth', str(args.t_former_depth),
        '--nf',             str(args.nf),
        '--Incep_depth',    str(args.Incep_depth),
        '--dataset',        args.dataset,
        '--db_in_channels', str(args.db_in_channels),
        '--num_classes',    str(args.num_classes),
    ]
    if args.mild_face_crop:
        cmd += ['--mild_face_crop']
    if args.normalize_db:
        cmd += ['--normalize_db']
    if args.db_pkl_path:
        cmd += ['--db_pkl_path', args.db_pkl_path]
    return cmd


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description='Inner 5-fold CV training + fixed held-out test evaluation.',
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )

    ex = parser.add_argument_group('Experiment')
    ex.add_argument('--results_dir', default=os.path.join(DECNET_ROOT, 'results'), type=str,
                    help='root directory where experiment folders are created')
    ex.add_argument('--run_name', default=None, type=str,
                    help='human-readable run name; auto-generated if omitted')

    an = parser.add_argument_group('Annotation')
    an.add_argument('--annotation_prefix', required=True, type=str,
                    help='common prefix of all annotation .txt files, '
                         'e.g. "annotation/PPB_CIR_V_DB_rgb_112_5s"; '
                         'expected files: {prefix}_test_fold{outer_fold}.txt, '
                         '{prefix}_cv{k}_train_fold{outer_fold}.txt, '
                         '{prefix}_cv{k}_val_fold{outer_fold}.txt')
    an.add_argument('--outer_fold', default=0, type=int,
                    help='outer fold index (selects the held-out test set)')
    an.add_argument('--n_inner_folds', default=5, type=int,
                    help='number of inner CV folds')

    dp = parser.add_argument_group('Data')
    dp.add_argument('--mild_face_crop', action='store_true', help='Use synchronized mild face crops for PPB training.')
    dp.add_argument('--normalize_db', action='store_true', help='Fit normalization separately inside each training fold.')
    dp.add_argument('--db_pkl_path', default=None, type=str,
                    help='driving-behaviour feature pickle')

    sh = parser.add_argument_group('Shared (train + test)')
    sh.add_argument('-t', default=5, type=int,
                    help='clip duration in seconds (must match annotation files and pickle)')
    sh.add_argument('--contrast', default='V-DB', choices=['V-DB', 'V', 'DB'])
    sh.add_argument('-b', '--batch-size', default=32, type=int)
    sh.add_argument('-j', '--workers',    default=8,  type=int)
    sh.add_argument('--s_former_depth', default=1,  type=int)
    sh.add_argument('--t_former_depth', default=3,  type=int)
    sh.add_argument('--nf',          default=32, type=int)
    sh.add_argument('--Incep_depth', default=6,  type=int)
    sh.add_argument('--dataset', default='PPB', choices=['PPB', 'AIDE'])
    sh.add_argument('--db_in_channels', default=8,  type=int,
                    help='8 for PPB, 195 for AIDE body keypoints')
    sh.add_argument('--num_classes',    default=7,  type=int,
                    help='7 for PPB, 5 for AIDE')
    sh.add_argument('--emotions', default=None, type=str,
                    help='comma-separated class names for test.py output')
    sh.add_argument('--label_groups_json', default=None, type=str,
                    help='path to label_groups.json; all groupings for the dataset '
                         'are run automatically in test.py')

    tr = parser.add_argument_group('Training (train.py only)')
    tr.add_argument('--epochs',   default=50,   type=int)
    tr.add_argument('--lr',       default=0.01, type=float)
    tr.add_argument('--momentum', default=0.9,  type=float)
    tr.add_argument('--wd',       default=1e-4, type=float, help='weight decay')
    tr.add_argument('--noise_A',  default=0.1,  type=float,
                    help='DB augmentation noise amplitude')
    tr.add_argument('--data_set', default=1,    type=int,
                    help='dataset index used in log filenames')

    args = parser.parse_args()

    # ------------------------------------------------------------------
    # Resolve annotation file paths
    # ------------------------------------------------------------------
    prefix   = args.annotation_prefix
    fold     = args.outer_fold
    n_inner  = args.n_inner_folds

    test_txt = f'{prefix}_test_fold{fold}.txt'
    inner_train_txts = [f'{prefix}_cv{k}_train_fold{fold}.txt' for k in range(n_inner)]
    inner_val_txts   = [f'{prefix}_cv{k}_val_fold{fold}.txt'   for k in range(n_inner)]

    # Verify all annotation files exist before starting
    missing = [p for p in [test_txt] + inner_train_txts + inner_val_txts
               if not os.path.isfile(p)]
    if missing:
        print('ERROR: annotation files not found:')
        for p in missing:
            print(f'  {p}')
        print(f'\nRun preprocess_ppb.py --fold {fold} --n_folds <N> first.')
        sys.exit(1)

    # ------------------------------------------------------------------
    # Resolve experiment directory
    # ------------------------------------------------------------------
    results_dir = os.path.abspath(args.results_dir)
    if args.run_name is None:
        ts_slug  = datetime.datetime.now().strftime('%Y-%m-%d_%H-%M-%S')
        run_name = (f'{ts_slug}_outerfold{fold}_inner{n_inner}'
                    f'_e{args.epochs}_b{args.batch_size}')
    else:
        run_name = args.run_name

    experiment_dir = resolve_experiment_dir(results_dir, run_name)
    eval_dir       = os.path.join(experiment_dir, 'eval')
    os.makedirs(experiment_dir, exist_ok=True)
    os.makedirs(eval_dir, exist_ok=True)

    print(f'Experiment directory: {experiment_dir}')

    # ------------------------------------------------------------------
    # Write initial metadata
    # ------------------------------------------------------------------
    metadata = {
        'run_name':     run_name,
        'created_at':   datetime.datetime.now().isoformat(timespec='seconds'),
        'completed_at': None,
        'status':       'training',
        'config': {
            'annotation_prefix': prefix,
            'outer_fold':        fold,
            'n_inner_folds':     n_inner,
            'db_pkl_path':       args.db_pkl_path,
            'normalize_db':      args.normalize_db,
            'mild_face_crop':    args.mild_face_crop,
            't':                 args.t,
            'contrast':          args.contrast,
            'batch_size':        args.batch_size,
            'workers':           args.workers,
            'epochs':            args.epochs,
            'lr':                args.lr,
            'momentum':          args.momentum,
            'weight_decay':      args.wd,
            'noise_A':           args.noise_A,
            's_former_depth':    args.s_former_depth,
            't_former_depth':    args.t_former_depth,
            'nf':                args.nf,
            'Incep_depth':       args.Incep_depth,
            'dataset':           args.dataset,
            'db_in_channels':    args.db_in_channels,
            'num_classes':       args.num_classes,
            'emotions':          args.emotions,
        },
        'inner_folds': {},
        'outputs':     {},
        'results':     {},
    }
    metadata_path = os.path.join(experiment_dir, 'metadata.json')
    write_metadata(metadata_path, metadata)

    # ------------------------------------------------------------------
    # Step 1 — Train each inner fold
    # ------------------------------------------------------------------
    best_ckpts = []    # one best checkpoint path per inner fold
    last_ckpts = []    # one last-epoch checkpoint path per inner fold (for training curves)

    for k in range(n_inner):
        inner_dir = os.path.join(experiment_dir, f'inner_fold_{k}')
        os.makedirs(inner_dir, exist_ok=True)

        train_cmd = build_train_cmd(
            args,
            train_txt=inner_train_txts[k],
            val_txt=inner_val_txts[k],
            output_dir=inner_dir,
        )

        rc = run_step(train_cmd, f'STEP 1/{n_inner} — INNER FOLD {k} TRAINING')
        if rc != 0:
            print(f'\nERROR: train.py exited with code {rc} on inner fold {k}. Aborting.')
            metadata['status'] = f'failed_training_fold{k} (exit {rc})'
            metadata['completed_at'] = datetime.datetime.now().isoformat(timespec='seconds')
            write_metadata(metadata_path, metadata)
            sys.exit(rc)

        # Locate the best checkpoint for this inner fold
        ckpt_pattern = os.path.join(inner_dir, 'checkpoint', '*model_best.pth')
        ckpts = sorted(glob.glob(ckpt_pattern))
        if not ckpts:
            print(f'\nERROR: no best checkpoint found in {inner_dir}/checkpoint/')
            metadata['status'] = f'failed_no_checkpoint_fold{k}'
            metadata['completed_at'] = datetime.datetime.now().isoformat(timespec='seconds')
            write_metadata(metadata_path, metadata)
            sys.exit(1)
        best_ckpt_k = ckpts[-1]
        best_ckpts.append(best_ckpt_k)

        # Locate the last-epoch checkpoint (has full training curve history).
        all_ckpts = sorted(glob.glob(os.path.join(inner_dir, 'checkpoint', '*model.pth')))
        last_ckpts_k = [p for p in all_ckpts if not p.endswith('_best.pth')]
        last_ckpts.append(last_ckpts_k[-1] if last_ckpts_k else best_ckpt_k)

        # Parse and record per-fold train metrics
        fold_train_metrics = parse_train_metrics(os.path.join(inner_dir, 'log'))
        train_logs   = sorted(glob.glob(os.path.join(inner_dir, 'log', '*-log.txt')))
        train_curves = sorted(glob.glob(os.path.join(inner_dir, 'log', '*-log.png')))
        metadata['inner_folds'][str(k)] = {
            'best_checkpoint': relpath(best_ckpt_k, experiment_dir),
            'train_log':       relpath(train_logs[-1],   experiment_dir) if train_logs   else None,
            'train_curve':     relpath(train_curves[-1], experiment_dir) if train_curves else None,
            **fold_train_metrics,
        }
        write_metadata(metadata_path, metadata)
        print(f'\nInner fold {k} — best checkpoint: {best_ckpt_k}')

    # ------------------------------------------------------------------
    # Step 2 — Evaluate: test.py in CV mode
    # ------------------------------------------------------------------
    metadata['status'] = 'evaluating'
    write_metadata(metadata_path, metadata)

    test_cmd = [
        PYTHON, 'test.py',
        '--cv_checkpoints',      *best_ckpts,
        '--cv_last_checkpoints', *last_ckpts,
        '--test_txt_path',       test_txt,
        '--output_dir',      eval_dir,
        '-t',                str(args.t),
        '--contrast',        args.contrast,
        '-b',                str(args.batch_size),
        '-j',                str(args.workers),
        '--s_former_depth',  str(args.s_former_depth),
        '--t_former_depth',  str(args.t_former_depth),
        '--nf',              str(args.nf),
        '--Incep_depth',     str(args.Incep_depth),
        '--dataset',         args.dataset,
        '--db_in_channels',  str(args.db_in_channels),
        '--num_classes',     str(args.num_classes),
    ]
    if args.emotions:
        test_cmd += ['--emotions', args.emotions]
    if args.db_pkl_path:
        test_cmd += ['--db_pkl_path', args.db_pkl_path]
    if args.label_groups_json:
        test_cmd += ['--label_groups_json', args.label_groups_json]

    rc = run_step(test_cmd, f'STEP 2/2 — EVALUATION (CV mode, outer fold {fold})')
    if rc != 0:
        print(f'\nERROR: test.py exited with code {rc}.')
        metadata['status'] = f'failed_evaluation (exit {rc})'
        metadata['completed_at'] = datetime.datetime.now().isoformat(timespec='seconds')
        write_metadata(metadata_path, metadata)
        sys.exit(rc)

    # ------------------------------------------------------------------
    # Finalise metadata
    # ------------------------------------------------------------------
    eval_log    = os.path.join(eval_dir, 'eval-log.txt')
    eval_fig    = os.path.join(eval_dir, 'combined-figure.png')
    eval_report = os.path.join(eval_dir, 'eval-report.md')

    if os.path.exists(eval_log):
        metadata['outputs']['eval_log']    = relpath(eval_log,    experiment_dir)
    if os.path.exists(eval_fig):
        metadata['outputs']['eval_figure'] = relpath(eval_fig,    experiment_dir)
    if os.path.exists(eval_report):
        metadata['outputs']['eval_report'] = relpath(eval_report, experiment_dir)

    metadata['results']      = parse_eval_metrics(eval_dir)
    metadata['status']       = 'completed'
    metadata['completed_at'] = datetime.datetime.now().isoformat(timespec='seconds')
    write_metadata(metadata_path, metadata)

    # ------------------------------------------------------------------
    # Final summary
    # ------------------------------------------------------------------
    print(f'\n{"=" * 62}')
    print(f'  EXPERIMENT COMPLETE')
    print(f'  Directory : {experiment_dir}')
    if metadata['results']:
        print('  Results   :')
        col = max(len(k) for k in metadata['results'])
        for k, v in metadata['results'].items():
            print(f'    {k:<{col}} : {v}')
    print('  Outputs   :')
    for k, v in metadata['outputs'].items():
        print(f'    {k:<16} : {v}')
    print(f'{"=" * 62}\n')


if __name__ == '__main__':
    main()
